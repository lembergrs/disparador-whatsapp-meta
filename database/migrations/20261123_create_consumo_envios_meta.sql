CREATE TABLE IF NOT EXISTS consumo_envios_meta (
    CEV_MessageId VARCHAR(255) NOT NULL PRIMARY KEY,
    CLI_ID INT NOT NULL,
    CEV_AnoMes CHAR(6) NOT NULL,
    CEV_DataConsumo DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS consumo_falhas_meta (
 CFM_MessageId VARCHAR(255) NOT NULL PRIMARY KEY,
 CFM_Codigo VARCHAR(64) NOT NULL,
 CFM_Data DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
